"""Writes the labels of the WHATWG Encoding Standard as a MoonBit file.

    python tools/gen_labels.py encodings.json label_data.mbt

encodings.json must be the file of whatwg/encoding commit
2c3853e461afd718be198772170d024e427aee21, the commit the CJK tables come
from (see tools/gen_index.py); its SHA-256 hash is checked. Download it with

    curl -fsSLO https://raw.githubusercontent.com/whatwg/encoding/2c3853e461afd718be198772170d024e427aee21/encodings.json

Output: encoding_for_label, which maps each of the 228 labels to the
`Encoding` variant of its encoding. Every label is in lower case ASCII, so
`Encoding::from_label` only needs to remove ASCII whitespace and fold ASCII
case before calling it.
"""

import hashlib
import json
import sys

SHA256 = "078212b3697f60b81225b6671bd9da2604497abff0aa8e96e4d46605c02ac9e7"

# The Encoding variant for the name of each encoding in the standard.
VARIANTS = {
    "UTF-8": "Utf8",
    "IBM866": "Ibm866",
    "ISO-8859-2": "Iso8859_2",
    "ISO-8859-3": "Iso8859_3",
    "ISO-8859-4": "Iso8859_4",
    "ISO-8859-5": "Iso8859_5",
    "ISO-8859-6": "Iso8859_6",
    "ISO-8859-7": "Iso8859_7",
    "ISO-8859-8": "Iso8859_8",
    "ISO-8859-8-I": "Iso8859_8I",
    "ISO-8859-10": "Iso8859_10",
    "ISO-8859-13": "Iso8859_13",
    "ISO-8859-14": "Iso8859_14",
    "ISO-8859-15": "Iso8859_15",
    "ISO-8859-16": "Iso8859_16",
    "KOI8-R": "Koi8R",
    "KOI8-U": "Koi8U",
    "macintosh": "Macintosh",
    "windows-874": "Windows874",
    "windows-1250": "Windows1250",
    "windows-1251": "Windows1251",
    "windows-1252": "Windows1252",
    "windows-1253": "Windows1253",
    "windows-1254": "Windows1254",
    "windows-1255": "Windows1255",
    "windows-1256": "Windows1256",
    "windows-1257": "Windows1257",
    "windows-1258": "Windows1258",
    "x-mac-cyrillic": "XMacCyrillic",
    "GBK": "Gbk",
    "gb18030": "Gb18030",
    "Big5": "Big5",
    "EUC-JP": "EucJp",
    "ISO-2022-JP": "Iso2022Jp",
    "Shift_JIS": "ShiftJis",
    "EUC-KR": "EucKr",
    "replacement": "Replacement",
    "UTF-16BE": "Utf16Be",
    "UTF-16LE": "Utf16Le",
    "x-user-defined": "XUserDefined",
}


def fail(message):
    sys.exit(f"gen_labels.py: {message}")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    in_path, out_path = sys.argv[1], sys.argv[2]
    with open(in_path, "rb") as f:
        data = f.read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        fail("encodings.json is not the file of whatwg/encoding 2c3853e")
    encodings = [e for group in json.loads(data) for e in group["encodings"]]
    if [e["name"] for e in encodings] != list(VARIANTS):
        fail("the encodings differ from the ones this script knows")
    labels = [label for e in encodings for label in e["labels"]]
    if len(set(labels)) != len(labels):
        fail("a label names two encodings")
    for label in labels:
        if not label.isascii() or label != label.lower() or label != label.strip():
            fail(f"label {label!r} is not lower case ASCII without spaces")

    out = [
        "// Generated by tools/gen_labels.py from encodings.json of the WHATWG",
        "// Encoding Standard (whatwg/encoding 2c3853e461afd718be198772170d024e427aee21).",
        "// Do not edit. Licensed under the BSD 3-Clause License, see",
        "// LICENSE-WHATWG and NOTICE.",
        "",
        "///|",
        f"/// The encoding each of the {len(labels)} labels of the Encoding Standard",
        "/// names. The labels are in lower case.",
        "fn encoding_for_label(label : StringView) -> Encoding? {",
        "  match label {",
    ]
    for e in encodings:
        patterns = " | ".join(f'"{label}"' for label in e["labels"])
        out.append(f"    {patterns} => Some({VARIANTS[e['name']]})")
    out += ["    _ => None", "  }", "}", ""]
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
